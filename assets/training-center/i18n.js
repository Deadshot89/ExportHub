function interpolate(value,vars){return String(value==null?'':value).replace(/\{\{\s*([\w.-]+)\s*\}\}/g,(_,key)=>vars&&Object.prototype.hasOwnProperty.call(vars,key)?String(vars[key]):'');}
function normalizeLanguage(value){const code=String(value||'').trim().toLowerCase().split(/[-_]/)[0];return Object.prototype.hasOwnProperty.call(packs,code)?code:'de';}
function currentLanguage(){
  const api=g.ExportHUBI18n;
  try{if(api&&typeof api.getLanguage==='function')return normalizeLanguage(api.getLanguage());}catch(_){}
  try{if(api&&typeof api.currentLanguage==='function')return normalizeLanguage(api.currentLanguage());}catch(_){}
  if(api&&typeof api.language==='string')return normalizeLanguage(api.language);
  try{const lang=g.document&&g.document.documentElement&&g.document.documentElement.lang;if(lang)return normalizeLanguage(lang);}catch(_){}
  return 'de';
}
function t(key,vars,language){
  const lang=normalizeLanguage(language||currentLanguage());
  const value=(packs[lang]&&packs[lang][key])??packs.de[key]??key;
  return interpolate(value,vars);
}

g.ExportHubTrainingCenterI18n=Object.freeze({packs,t,currentLanguage,normalizeLanguage});
