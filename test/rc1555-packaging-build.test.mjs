import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

function read(path){return fs.readFileSync(path,'utf8');}
const mainBuild=read('.github/rc1112/build-three-env.mjs');
const finalIntegrator=read('.github/rc1506/build-three-env.mjs');
const packagingBuild=read('.github/rc1555/integrate-packaging-masterdata.mjs');
const packBuild=read('.github/packmeldungen/build-three-env.mjs');

test('RC1555 main three-environment release chain copies every packaging masterdata runtime and locale pack',()=>{
  assert.match(mainBuild,/integrateCoverageAdmin\(ROOT,OUT\)/,'RC1112 must execute the final RC1506 integration stage');
  assert.match(finalIntegrator,/integratePackagingMasterdata/,'final RC1506 integration stage must execute RC1555 packaging integration');
  for(const rel of [
    'assets/rc1555-packaging-store.js',
    'assets/rc1555-packaging-management.js',
    'assets/rc1555-packaging-management.css'
  ])assert.ok(packagingBuild.includes(rel),`RC1555 build integration missing ${rel}`);
  assert.match(packagingBuild,/assets\/i18n\/rc1555-packaging-masterdata/,'RC1555 build integration must copy the central locale-pack directory');
  for(const lang of ['de','en','pl','es','fr','it'])assert.ok(packagingBuild.includes(`'${lang}'`),`RC1555 build integration must carry ${lang} locale pack`);
});

test('RC1555 final build injects i18n then canonical store then masterdata management into all app environments',()=>{
  assert.match(packagingBuild,/exporthub-rc1555-packaging-store/,'canonical store tag missing');
  assert.match(packagingBuild,/exporthub-rc1555-packaging-management/,'management tag missing');
  assert.match(packagingBuild,/rc1555-packaging-store\.js\?v=1555/,'canonical store src missing');
  assert.match(packagingBuild,/rc1555-packaging-management\.js\?v=1555/,'management src missing');
  assert.match(packagingBuild,/\['index\.html','TESTVERSION\.html','demo\.html'\]/,'three environment html loop missing');
  assert.match(packagingBuild,/i18n<0\|\|store<=i18n/,'central i18n must precede canonical store');
  assert.match(packagingBuild,/management<=store/,'canonical store must precede management runtime');
});

test('RC1555 packmeldungen release copies canonical packaging store beside the public pack runtime',()=>{
  assert.match(packBuild,/['"]rc1555-packaging-store\.js['"]/,'PACK_ASSETS must include rc1555-packaging-store.js');
  assert.match(packBuild,/['"]packaging-catalog\.js['"]/,'PACK_ASSETS must continue to copy compatibility catalog adapter');
  assert.match(packBuild,/path\.join\(root,'pack\.html'\)/,'pack build must carry the updated pack page');
});

test('RC1555 source app pages contain no duplicate management runtime before build injection',()=>{
  // demo.html is generated by the release builder; source pages must stay clean so the final integrator owns injection.
  for(const file of ['index.html','TESTVERSION.html']){
    const html=read(file);
    assert.ok((html.match(/exporthub-rc1555-packaging-management/g)||[]).length<=1,`${file}: duplicate RC1555 management tags`);
    assert.ok((html.match(/exporthub-rc1555-packaging-store/g)||[]).length<=1,`${file}: duplicate RC1555 store tags`);
  }
});