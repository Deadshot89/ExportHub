async function ratePublicCreate(ctx,normalized){
 // Keine Client-IP-Header als Sicherheitsgrenze verwenden: SWA bestaetigt deren
 // Authentizitaet fuer diesen API-Pfad nicht. Alle Quoten sind serverseitig atomar.
 const hour=new Date().toISOString().slice(0,13).replace(/[-T:]/g,'');
 // Derselbe Kunde und dieselbe Sendungsnummer koennen nicht unbegrenzt
 // neue Datensaetze erzeugen, auch nicht mit gefaelschten Proxy-Headern.
 const identity=publicHash(JSON.stringify([normalized.customer.toLocaleLowerCase('de-DE'),
  normalized.shipmentNumber.toLocaleLowerCase('de-DE')])).slice(0,32);
 const buckets=[{key:'shipment-'+identity,limit:3},{key:'global',limit:40}];
 for(const bucket of buckets){
  const blob=ctx.container.getBlockBlobClient(ctx.prefix+'public-rate/'+hour+'/'+bucket.key+'.json');
  let accepted=false;
  for(let attempt=0;attempt<6;attempt++){
   let count=0,etag=null;
   try{
    const current=await blob.download(0),parts=[];
    for await(const part of current.readableStreamBody)parts.push(Buffer.from(part));
    count=Number(JSON.parse(Buffer.concat(parts).toString('utf8')).count)||0;
    etag=current.etag;
   }catch(e){if(e.statusCode!==404)throw e}
   if(count>=bucket.limit)fail('PUBLIC_RATE_LIMIT','Zu viele neue Dokumentationen. Bitte spaeter erneut versuchen.',429);
   try{
    await blob.uploadData(Buffer.from(JSON.stringify({count:count+1})),{
     blobHTTPHeaders:{blobContentType:'application/json'},
     conditions:etag?{ifMatch:etag}:{ifNoneMatch:'*'}
    });
    accepted=true;break;
   }catch(e){if(e.statusCode!==409&&e.statusCode!==412)throw e}
  }
  if(!accepted)fail('PUBLIC_RATE_RETRY','Neuerfassung temporaer nicht verfuegbar.',503);
 }
}
