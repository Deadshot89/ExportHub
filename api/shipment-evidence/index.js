function verifiedDeploymentEnvironment(){
 const filename=process.env.EXPORTHUB_RELEASE_METADATA_PATH
  ?path.resolve(process.env.EXPORTHUB_RELEASE_METADATA_PATH)
  :path.join(__dirname,'..','release-metadata.json');
 try{
  const meta=JSON.parse(fs.readFileSync(filename,'utf8'));
  if(meta&&typeof meta==='object'&&!Array.isArray(meta)&&
     /^[0-9a-f]{40}$/i.test(meta.buildId||'')&&
     typeof meta.visibleRelease==='string'&&meta.visibleRelease.trim()&&
     typeof meta.technicalBuild==='string'&&meta.technicalBuild.trim()&&
     typeof meta.builtAt==='string'&&meta.builtAt.trim()&&
     (meta.environment==='testservice'||meta.environment==='production'))
    return meta.environment;
 }catch(_){}
 return null;
}
